IMAGE_EXTENSIONS = {
    ".png",
    ".jpg",
    ".jpeg",
    ".bmp",
    ".webp",
}


def windows_safe_basename(value):

    text = str(value).strip()

    text = text.strip('"').strip("'")

    text = text.replace("\\", "/")

    return text.split("/")[-1]


def build_image_index(search_root):

    print("\nBuilding image index from:")
    print(search_root)

    index = {}

    total = 0

    for root, dirs, files in os.walk(search_root):

        for filename in files:

            extension = os.path.splitext(
                filename
            )[1].lower()

            if extension not in IMAGE_EXTENSIONS:
                continue

            full_path = os.path.join(
                root,
                filename,
            )

            index.setdefault(
                filename.lower(),
                [],
            ).append(
                full_path
            )

            total += 1

    print("Images indexed:", total)

    return index


def resolve_paths_for_dataframe(
    df,
    image_column,
    csv_path,
):

    original_values = df[
        image_column
    ].astype(str).tolist()

    # First determine whether all paths already work.
    direct_paths = []

    all_direct = True

    for value in original_values:

        cleaned = str(value).strip().strip('"').strip("'")

        if os.path.isfile(cleaned):

            direct_paths.append(cleaned)

        else:

            all_direct = False
            break

    if all_direct:

        df["_image_path"] = direct_paths

        print("\nAll CSV image paths already exist.")

        return df

    # Search near the CSV first.
    csv_folder = os.path.dirname(
        csv_path
    )

    candidate_roots = [
        csv_folder,
        os.path.dirname(csv_folder),
        os.path.dirname(
            os.path.dirname(csv_folder)
        ),
        DRIVE_ROOT,
    ]

    # Remove duplicates while preserving order.
    candidate_roots = list(
        dict.fromkeys(
            candidate_roots
        )
    )

    unresolved = list(
        range(
            len(original_values)
        )
    )

    resolved = {
    }

    for search_root in candidate_roots:

        if not unresolved:
            break

        if not os.path.isdir(search_root):
            continue

        image_index = build_image_index(
            search_root
        )

        still_unresolved = []

        for row_index in unresolved:

            original = original_values[
                row_index
            ]

            filename = windows_safe_basename(
                original
            )

            matches = image_index.get(
                filename.lower(),
                [],
            )

            if len(matches) == 1:

                resolved[
                    row_index
                ] = matches[0]

                continue

            if len(matches) > 1:

                original_normalized = (
                    original
                    .replace("\\", "/")
                    .lower()
                )

                original_parts = [
                    part
                    for part
                    in original_normalized.split("/")
                    if part
                ]

                chosen = None

                # Try progressively longer suffixes.
                for suffix_length in [
                    4,
                    3,
                    2,
                ]:

                    if len(original_parts) < suffix_length:
                        continue

                    suffix = "/".join(
                        original_parts[
                            -suffix_length:
                        ]
                    )

                    suffix_matches = [
                        match
                        for match
                        in matches
                        if match.replace(
                            "\\",
                            "/",
                        ).lower().endswith(
                            suffix
                        )
                    ]

                    if len(suffix_matches) == 1:

                        chosen = suffix_matches[0]

                        break

                if chosen is not None:

                    resolved[
                        row_index
                    ] = chosen

                    continue

            still_unresolved.append(
                row_index
            )

        unresolved = still_unresolved

    if unresolved:

        print("\nUNRESOLVED IMAGES:")

        for row_index in unresolved[:30]:

            print(
                row_index,
                original_values[
                    row_index
                ],
            )

        raise FileNotFoundError(
            f"{len(unresolved)} image paths could not be resolved in Google Drive."
        )

    resolved_paths = [
        resolved[index]
        for index
        in range(
            len(original_values)
        )
    ]

    df["_image_path"] = resolved_paths

    return df


