def move_batch_to_device(
    batch,
):

    moved = {}

    for key, value in batch.items():

        if not torch.is_tensor(
            value
        ):

            moved[key] = value

            continue

        if value.dtype.is_floating_point:

            moved[key] = value.to(
                device=DEVICE,
                dtype=MODEL_DTYPE,
            )

        else:

            moved[key] = value.to(
                DEVICE
            )

    return moved


