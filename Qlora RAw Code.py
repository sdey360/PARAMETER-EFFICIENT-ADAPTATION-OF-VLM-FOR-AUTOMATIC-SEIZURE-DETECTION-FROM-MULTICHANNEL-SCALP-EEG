# ==================================================================================================
# 40. TRAINING COLLATOR
#
# Only assistant target tokens contribute to loss.
# ==================================================================================================

class MedGemmaTrainingCollator:

    def __init__(
        self,
        processor,
    ):

        self.processor = processor

    def __call__(
        self,
        examples,
    ):

        if len(examples) != 1:

            raise ValueError(
                "This pipeline expects physical batch size = 1."
            )

        example = examples[0]

        image_path = example[
            "image_path"
        ]

        label = int(
            example[
                "label"
            ]
        )

        target_text = label_to_target_text(
            label
        )

        with Image.open(
            image_path
        ) as opened_image:

            image = opened_image.convert(
                "RGB"
            )

            prompt_messages = build_prompt_messages(
                image
            )

            prompt_inputs = self.processor.apply_chat_template(
                prompt_messages,
                add_generation_prompt=True,
                tokenize=True,
                return_dict=True,
                return_tensors="pt",
            )

            prompt_length = int(
                prompt_inputs[
                    "input_ids"
                ].shape[
                    1
                ]
            )

            full_messages = build_training_messages(
                image,
                target_text,
            )

            full_inputs = self.processor.apply_chat_template(
                full_messages,
                add_generation_prompt=False,
                tokenize=True,
                return_dict=True,
                return_tensors="pt",
            )

        full_ids = full_inputs[
            "input_ids"
        ]

        prompt_ids = prompt_inputs[
            "input_ids"
        ]

        if full_ids.shape[1] <= prompt_length:

            raise RuntimeError(
                "Full sequence contains no assistant target tokens."
            )

        if not torch.equal(
            full_ids[
                :,
                :prompt_length
            ],
            prompt_ids,
        ):

            raise RuntimeError(
                "MedGemma chat-template prefix mismatch. "
                "Stopping to avoid incorrect loss masking."
            )

        labels = full_ids.clone()

        labels[
            :,
            :prompt_length
        ] = -100

        if int(
            (
                labels != -100
            ).sum()
        ) <= 0:

            raise RuntimeError(
                "No target tokens remain after loss masking."
            )

        full_inputs[
            "labels"
        ] = labels

        return full_inputs


