def load_and_standardize_metadata(
    csv_path,
    dataset_name,
    dataset_type,
):

    print("\n" + "=" * 100)
    print("LOADING:", dataset_name)
    print("=" * 100)

    if not os.path.isfile(csv_path):

        raise FileNotFoundError(
            csv_path
        )

    df = pd.read_csv(
        csv_path
    )

    print("CSV:", csv_path)
    print("Rows:", len(df))
    print("Columns:", list(df.columns))

    image_column = detect_image_path_column(
        df,
        dataset_type,
    )

    label_column = detect_label_column(
        df
    )

    print("Image column:", image_column)
    print("Label column:", label_column)

    df["_label"] = df[
        label_column
    ].apply(
        normalize_ground_truth_label
    )

    if df["_label"].isna().any():

        bad = df[
            df["_label"].isna()
        ]

        print(
            bad[
                [label_column]
            ].drop_duplicates()
        )

        raise ValueError(
            "Some labels could not be interpreted."
        )

    df["_label"] = df[
        "_label"
    ].astype(int)

    df = resolve_paths_for_dataframe(
        df,
        image_column,
        csv_path,
    )

    missing = [
        path
        for path
        in df["_image_path"]
        if not os.path.isfile(path)
    ]

    if missing:

        raise FileNotFoundError(
            f"{len(missing)} images are missing."
        )

    duplicate_count = int(
        df[
            "_image_path"
        ].duplicated().sum()
    )

    if duplicate_count > 0:

        raise ValueError(
            f"{duplicate_count} duplicate image paths were detected."
        )

    seizure_count = int(
        (
            df["_label"] == 1
        ).sum()
    )

    non_seizure_count = int(
        (
            df["_label"] == 0
        ).sum()
    )

    print("\nSeizure     :", seizure_count)
    print("Non-seizure :", non_seizure_count)
    print("Total        :", len(df))

    return (
        df,
        image_column,
        label_column,
    )


