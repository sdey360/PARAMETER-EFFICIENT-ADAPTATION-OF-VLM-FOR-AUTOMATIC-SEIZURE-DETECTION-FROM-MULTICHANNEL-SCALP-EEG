@torch.no_grad()
def calculate_validation_loss():

    model.eval()

    losses = []

    progress = tqdm(
        validation_loss_loader,
        desc="Validation loss",
        leave=False,
    )

    for batch in progress:

        batch = move_batch_to_device(
            batch
        )

        with autocast_context():

            outputs = model(
                **batch
            )

            loss = outputs.loss

        loss_value = float(
            loss
            .detach()
            .float()
            .cpu()
        )

        losses.append(
            loss_value
        )

        progress.set_postfix(
            loss=f"{loss_value:.4f}"
        )

        del batch
        del outputs
        del loss

    return float(
        np.mean(
            losses
        )
    )


