def normalize_ground_truth_label(value):

    if pd.isna(value):
        return None

    if isinstance(
        value,
        (
            int,
            np.integer,
        ),
    ):

        if int(value) == 1:
            return 1

        if int(value) == 0:
            return 0

    if isinstance(
        value,
        (
            float,
            np.floating,
        ),
    ):

        if float(value) == 1.0:
            return 1

        if float(value) == 0.0:
            return 0

    text = str(value).strip().lower()

    text = text.replace("_", " ")

    text = text.replace("–", "-")

    text = re.sub(
        r"\s+",
        " ",
        text,
    )

    # Non-seizure MUST be checked first.
    if text in {
        "0",
        "0.0",
        "non seizure",
        "non-seizure",
        "nonseizure",
        "normal",
        "interictal",
        "ns",
    }:
        return 0

    if (
        "non" in text
        and
        "seizure" in text
    ):
        return 0

    if text in {
        "1",
        "1.0",
        "seizure",
        "ictal",
        "sz",
    }:
        return 1

    if "seizure" in text:
        return 1

    return None


